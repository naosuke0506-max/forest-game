// 長い言葉から先に探す（「楯劍騎士」の中の「劍騎士」、「刻之長」の中の「刻」に先に付けないように）
const KEYS = Object.keys(READINGS).sort((a, b) => b.length - a.length);
const PATTERN = new RegExp(KEYS.join('|'), 'g');
const esc = (s) => String(s).replace(/[&<>"]/g, (c) => ({ '&': '&amp;', '<': '&lt;', '>': '&gt;', '"': '&quot;' }[c]));

/** 文字（HTML ではない）の中の読みにくい漢字に、ふりがなを付けた HTML を返す */
export function ruby(text) {
  return esc(text).replace(PATTERN, (w) => `<ruby>${w}<rt>${READINGS[w]}</rt></ruby>`);
}

const HAS = new RegExp(KEYS.join('|'));

/**
 * root の中の selector に合う部品の、すぐ下の文字（小さな添え書き small などの中は見ない）にふりがなを付ける。
 * もう付いている部品はそのまま（何度呼んでもよい）。index.html の data-ruby の部品・圖鑑・試合の前に選ぶ画面で使う
 */
export function rubyIn(root, selector) {
  for (const el of root.querySelectorAll(selector)) {
    if (el.querySelector('ruby')) continue;
    for (const n of [...el.childNodes]) {
      if (n.nodeType !== 3 || !HAS.test(n.nodeValue)) continue;
      const box = document.createElement('span');
      box.innerHTML = ruby(n.nodeValue);
      n.replaceWith(...box.childNodes);
    }
  }
}
